export function getBondLength(el1: string, el2: string, bondType: string): number | undefined {
  const sep = bondType === 'double' ? '=' : bondType === 'triple' ? '≡' : '-';
  const key1 = `${el1}${sep}${el2}`;
  const key2 = `${el2}${sep}${el1}`;
  return BOND_LENGTHS[key1] ?? BOND_LENGTHS[key2];
}
